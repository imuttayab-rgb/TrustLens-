"""Render the ER diagram from the SQLAlchemy models (P0-09, feeds D-04).

Mermaid rather than Graphviz on purpose: `eralchemy` and
`sqlalchemy_schemadisplay` both need a system Graphviz install, which is one
more thing to get working on a lab machine on submission week. Mermaid is
text, renders inline on GitHub, pastes into the report, and diffs in review.

The diagram is generated from the models rather than drawn by hand, so it
cannot drift from the schema it documents - `docs/05` already claims 30 tables
where the migration creates 40, which is exactly the failure this avoids.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sqlalchemy import Table

from trustlens.db.models import Base

#: Mermaid has no bare "UUID"; these keep the diagram readable without
#: pretending to be exact DDL. Anything unmapped falls back to the SQL type
#: name with the parameters stripped.
_TYPE_ALIASES = {
    "UUID": "uuid",
    "VARCHAR": "varchar",
    "TEXT": "text",
    "BOOLEAN": "bool",
    "INTEGER": "int",
    "SMALLINT": "smallint",
    "BIGINT": "bigint",
    "NUMERIC": "numeric",
    "DOUBLE PRECISION": "float",
    "TIMESTAMP": "timestamptz",
    "DATETIME": "timestamptz",
    "DATE": "date",
    "JSONB": "jsonb",
    "BYTEA": "bytea",
    "INET": "inet",
}


def _type_name(column: object) -> str:
    raw = str(getattr(column, "type", "")).upper()
    base = raw.split("(")[0].strip()
    return _TYPE_ALIASES.get(base, base.lower() or "unknown")


def _column_line(column: object) -> str:
    name = getattr(column, "name", "?")
    parts = [_type_name(column), str(name)]
    if getattr(column, "primary_key", False):
        parts.append("PK")
    elif getattr(column, "foreign_keys", None):
        parts.append("FK")
    return "    " + " ".join(parts)


def render(tables: list[Table]) -> str:
    lines: list[str] = ["erDiagram"]

    for table in tables:
        lines.append(f"  {table.name} {{")
        lines.extend(_column_line(c) for c in table.columns)
        lines.append("  }")

    lines.append("")

    # One edge per foreign key. Identifying vs non-identifying is approximated
    # by nullability: a required parent is drawn as a solid line.
    seen: set[tuple[str, str, str]] = set()
    for table in tables:
        for column in table.columns:
            for fk in column.foreign_keys:
                parent = fk.column.table.name
                edge = (parent, table.name, column.name)
                if edge in seen:
                    continue
                seen.add(edge)
                connector = "||--o{" if not column.nullable else "||--o|"
                lines.append(f"  {parent} {connector} {table.name} : {column.name}")

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-o",
        "--out",
        type=Path,
        default=Path("docs/diagrams/erd.md"),
        help="Where to write the diagram.",
    )
    args = parser.parse_args()

    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    if not tables:
        print(
            "!! No tables on the metadata - is trustlens.db.models importable?",
            file=sys.stderr,
        )
        return 1

    body = render(tables)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "<!-- Generated by tools/erd/generate.py. Do not edit by hand. -->\n"
        f"# TrustLens ER diagram\n\n{len(tables)} tables.\n\n```mermaid\n{body}```\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"==> {args.out} ({len(tables)} tables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
