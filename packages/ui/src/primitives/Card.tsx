import * as React from 'react';
import { cn } from '../lib/cn';

export const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        // Translucent over the ambient wash rather than opaque: on a near-black
        // surface an opaque panel reads as a hole, a translucent one as glass
        // sitting above it. The ring replaces a drop shadow, which is invisible
        // at this value range.
        'border-border/70 bg-card/60 text-card-foreground rounded-xl border backdrop-blur-xl',
        'shadow-[0_0_0_1px_hsl(var(--brand)/0.04),0_18px_50px_-30px_hsl(var(--brand)/0.25)]',
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = 'Card';

export const CardHeader = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div ref={ref} className={cn('flex flex-col space-y-1.5 p-6', className)} {...props} />
  ),
);
CardHeader.displayName = 'CardHeader';

